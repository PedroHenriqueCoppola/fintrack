<?php

namespace App\Support;

class NameNormalizer
{
    /**
     * Compare names ignoring case and Portuguese accents.
     * The PHP image has no ext-intl, so the folding is an explicit map.
     */
    public function key(string $name): string
    {
        $folded = mb_strtolower(trim($name));

        return strtr($folded, [
            'á' => 'a', 'à' => 'a', 'â' => 'a', 'ã' => 'a', 'ä' => 'a',
            'é' => 'e', 'è' => 'e', 'ê' => 'e', 'ë' => 'e',
            'í' => 'i', 'ì' => 'i', 'î' => 'i', 'ï' => 'i',
            'ó' => 'o', 'ò' => 'o', 'ô' => 'o', 'õ' => 'o', 'ö' => 'o',
            'ú' => 'u', 'ù' => 'u', 'û' => 'u', 'ü' => 'u',
            'ç' => 'c', 'ñ' => 'n',
        ]);
    }
}
